#!/usr/bin/env node
/* Blissverktyget — brings the writing rules, grammar engine and synonyms of
   Bliss-glosor (johbom/blissmaiker) into Skriv. Not published (only workbench/ is).

     node tools/build-skriv.js <path to a blissmaiker checkout>

   Writes, from that checkout:
     workbench/js/shared/bliss-grammar.js   src/vendor/bliss-grammar.js (BlissEngine's Grammar /
                                            composeSentence), as a plain script: window.BlissGrammar
     workbench/js/shared/bliss-skriv.js     src/glosor-skriv.js unchanged, behind a small prelude
                                            that builds its word deck from this project's data:
                                            window.BlissSkriv
     workbench/js/data/bliss-skriv-data.js  the deck: which BCI-AV ids, SUC 3.0 frequency, and the
                                            head words Bliss-glosor picks (only where they differ
                                            from the first gloss)
     workbench/js/data/bliss-synonymer.js   Swesaurus synonyms (copied)
     workbench/js/data/bliss-harledda.js    derived verbs from SUC 3.0 (copied)

   The drawing engine and the symbol data are NOT copied: this project's
   js/engine/ and js/data/bliss-data.js are byte-identical to the originals
   Bliss-glosor locks (scripts/bliss-motor.lock.json). The script checks that,
   and the Swedish morphology (js/shared/sv-morph.js is the same analysis as its
   src/vendor/bliss-lemma.js), and at the end that both apps write the same
   sentences the same way. */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const crypto = require('crypto');
const { execSync } = require('child_process');

const REF = process.argv[2];
if (!REF || !fs.existsSync(path.join(REF, 'src', 'glosor-skriv.js'))) {
  console.error('usage: node tools/build-skriv.js <path to a blissmaiker checkout>');
  process.exit(2);
}
const ROOT = path.join(__dirname, '..');
const WB = path.join(ROOT, 'workbench');
const ref = (f) => fs.readFileSync(path.join(REF, f), 'utf8');
const wb = (f) => fs.readFileSync(path.join(WB, f), 'utf8');
const write = (f, s) => { fs.writeFileSync(path.join(WB, f), s); console.log(`${f}  ${(s.length / 1024).toFixed(1)} kB`); };
let rev = 'unknown';
try { rev = execSync('git rev-parse --short HEAD', { cwd: REF }).toString().trim(); } catch (_) {}
const HEAD = (from) => `// AUTO-GENERATED by tools/build-skriv.js from Bliss-glosor (johbom/blissmaiker ${rev}, ${from}) — do not edit by hand.\n`;

/* ---- 1. the engine and the data must be the originals Bliss-glosor uses ---- */
const sha = (s) => crypto.createHash('sha256').update(s).digest('hex');
const lock = JSON.parse(ref('scripts/bliss-motor.lock.json')).files;
for (const [f, mine] of [['bliss-shapes.js', 'js/engine/bliss-shapes.js'], ['bliss-engine.js', 'js/engine/bliss-engine.js'], ['bliss-data.js', 'js/data/bliss-data.js']]) {
  if (sha(fs.readFileSync(path.join(WB, mine))) !== lock[f]) throw new Error(`${mine} is not the original Bliss-glosor locks (${f})`);
}
console.log('engine and BCI-AV data: identical to the originals Bliss-glosor locks');

/* ---- 2. the grammar engine, as a plain script ---- */
const grammar = ref('src/vendor/bliss-grammar.js').replace(/^export (function|const|let|class) /gm, '$1 ');
write('js/shared/bliss-grammar.js', HEAD('src/vendor/bliss-grammar.js') +
  '// Indicators placed by BlissEngine\'s Grammar/composeSentence (Fundamental Rules 4.3.3/4.3.4/7.1).\n' +
  '(() => {\n' + grammar +
  '\nwindow.BlissGrammar = { INDICATOR_RECORDS, FORM_CHOICES, IND_TENSE, indJoin, indToggle, Grammar, indicatorGlyph, composeSentence };\n})();\n');

/* ---- 3. Bliss-glosor's deck, in Node ---- */
const { ladda } = require(path.join(REF, 'tests', 'ladda.js'));
const { G } = ladda();
const deck = G.deck;

/* ---- 4. the writing rules: src/glosor-skriv.js unchanged, behind a prelude ---- */
// The prelude builds the same deck from this project's data (bliss-data.js, glosses.js) and
// bliss-skriv-data.js; the defaults below are the rules src/glosor.js uses, and the data
// file carries every place where Bliss-glosor's deck differs from them.
const PRELUDE = `
/* Prelude (Blissverktyget): the word deck src/glosor-skriv.js reads as window.Glosor —
   built from js/data/bliss-data.js, js/data/glosses.js and js/data/bliss-skriv-data.js.
   Needs BLISS_DATA, BLISS_GLOSSES, BLISS_SKRIV_DATA and SvMorph (js/shared/sv-morph.js,
   the same Swedish morphology as Bliss-glosor's bliss-lemma.js). */
(() => {
  const SRC = window.BLISS_SKRIV_DATA || (typeof BLISS_SKRIV_DATA !== 'undefined' ? BLISS_SKRIV_DATA : null);
  if (!SRC) return;
  if (!window.BlissLemma && typeof SvMorph !== 'undefined') window.BlissLemma = SvMorph;
  ${splitSynsSrc()}
  ${enSynsSrc()}
  const byId = new Map(BLISS_DATA.map((s) => [s.id, s]));
  const SV = (typeof BLISS_GLOSSES !== 'undefined' && BLISS_GLOSSES.sv) || {};
  let LANG = 'sv';
  const deck = new Map();
  for (const [k, row] of Object.entries(SRC.deck)) {
    const s = byId.get(+k);
    if (!s) continue;
    const [freq, over] = Array.isArray(row) ? row : [row, null];
    const v = { id: s.id, en: s.n, sv: SV[s.id] || s.n, c: s.c, e: s.e };
    const synsSv = (over && over.synsSv) || splitSyns(v.sv).map((x) => x.replace(/\\s*\\(etc\\)/, '').trim()).filter(Boolean);
    const synsEn = (over && over.synsEn) || enSyns(v.en);
    const c = { id: v.id, v, freq, synsSv, synsEn,
      headSv: (over && over.headSv) || [synsSv[0] || '', 0], headEn: (over && over.headEn) || [synsEn[0] || '', 0] };
    Object.defineProperties(c, {
      word: { get: () => (LANG === 'en' ? c.headEn[0] : c.headSv[0]) || c.v.sv },
      wordSv: { get: () => c.headSv[0] || c.v.sv },
    });
    deck.set(v.id, c);
  }
  window.BlissSkriv = { deck, lang: () => LANG, setLang: (l) => { LANG = l === 'en' ? 'en' : 'sv'; } };
})();
`;
function splitSynsSrc() {
  const src = ref('src/glosor.js');
  const i = src.indexOf('function splitSyns('), j = src.indexOf('\n}\n', i) + 2;
  return src.slice(i, j);
}
function enSynsSrc() {
  const src = ref('src/glosor.js');
  const i = src.indexOf('function enSyns('), j = src.indexOf('\n}\n', i) + 2;
  return src.slice(i, j);
}
let skriv = ref('src/glosor-skriv.js');
const GLOSOR = 'const G = window.Glosor;';
if (!skriv.includes(GLOSOR)) throw new Error('src/glosor-skriv.js: the line "' + GLOSOR + '" has changed');
skriv = skriv.replace(GLOSOR, 'const G = window.BlissSkriv;\nif (!G) return;');
write('js/shared/bliss-skriv.js', HEAD('src/glosor-skriv.js') +
  '// The writing rules of Bliss-glosor\'s "Skriv en egen mening", used by Skriv: text -> Bliss words with\n' +
  '// alternatives (phrases, "ska" + verb = future, articles that can be left out, synonyms, derived verbs).\n' +
  PRELUDE + skriv);

/* ---- 5. the deck data: frequency, and Bliss-glosor's words where they differ from the defaults ---- */
const ctx = { console };
vm.createContext(ctx);
vm.runInContext(`${splitSynsSrc()}\n${enSynsSrc()}`, ctx);
const SVG = {};
{
  const c2 = { console };
  vm.createContext(c2);
  vm.runInContext(wb('js/data/glosses.js').replace(/^(const|let) (BLISS_GLOSSES|GLOSS_LANGS)\b/gm, 'var $2'), c2);
  Object.assign(SVG, c2.BLISS_GLOSSES.sv);
}
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b);
const out = {};
let overs = 0;
for (const c of deck.values()) {
  const sv = SVG[c.id] || c.v.en;
  const synsSv = ctx.splitSyns(sv).map((x) => x.replace(/\s*\(etc\)/, '').trim()).filter(Boolean);
  const synsEn = ctx.enSyns(c.v.en);
  const over = {};
  if (!same(synsSv, c.synsSv)) over.synsSv = c.synsSv;
  if (!same(synsEn, c.synsEn)) over.synsEn = c.synsEn;
  if (!same([c.synsSv[0] || '', 0], c.headSv)) over.headSv = c.headSv;
  if (!same([c.synsEn[0] || '', 0], c.headEn)) over.headEn = c.headEn;
  if (Object.keys(over).length) { overs++; out[c.id] = [c.freq, over]; } else out[c.id] = c.freq;
}
write('js/data/bliss-skriv-data.js', HEAD('the word deck of src/glosor.js') +
  '// BCI-AV ids Bliss-glosor writes with -> SUC 3.0 frequency (Språkbanken Text, CC BY 4.0), or\n' +
  '// [frequency, {synsSv, synsEn, headSv, headEn}] where its words differ from the plain glosses.\n' +
  `window.BLISS_SKRIV_DATA = { deck: ${JSON.stringify(out)} };\n`);
console.log(`  ${deck.size} words, ${overs} with their own head word or synonyms`);

/* ---- 6. synonyms and derived verbs, copied ---- */
write('js/data/bliss-synonymer.js', ref('src/vendor/bliss-synonymer.js'));
write('js/data/bliss-harledda.js', ref('src/vendor/bliss-harledda.js'));

/* ---- 7. the same morphology, and the same sentences ---- */
const mine = vm.createContext({ console, window: {} });
const run = (f) => vm.runInContext(wb(f).replace(/^(const|let) (BLISS_DATA|BLISS_GLOSSES|GLOSS_LANGS|SvMorph)\b/gm, 'var $2'), mine, { filename: f });
for (const f of ['js/data/bliss-data.js', 'js/data/glosses.js', 'js/shared/sv-morph.js', 'js/data/bliss-skriv-data.js',
  'js/data/bliss-synonymer.js', 'js/data/bliss-harledda.js', 'js/shared/bliss-skriv.js']) run(f);
const theirs = vm.createContext({ console, window: {} });
vm.runInContext(ref('src/vendor/bliss-lemma.js'), theirs);
const A = mine.SvMorph, B = theirs.window.BlissLemma, senses = (k) => A.senses(k);
let lemmaDiff = 0;
for (const g of Object.values(SVG)) for (const w0 of g.split(',')) {
  const w = w0.replace(/\(.*?\)/g, '').trim().toLowerCase();
  if (!w || /\s/.test(w)) continue;
  for (const t of [w, w + 'en', w + 'et', w + 'ar', w + 'er', w + 'arna', w + 'de', w + 'te', w + 'r'])
    if (!same(A.analyze(t, senses), B.analyze(t, senses))) lemmaDiff++;
}
if (lemmaDiff) throw new Error(`sv-morph.js and Bliss-glosor's bliss-lemma.js differ on ${lemmaDiff} words: port src/lemmatize.js again`);
console.log('morphology: sv-morph.js gives the same analyses as Bliss-glosor');
const S = mine.window.BlissSkriv;
const key = (o) => (o ? (o.skip ? 'skip' : o.text ? 'text' : o.key) : null);
const texts = JSON.parse(ref('data/meningar.json')).meningar.map((m) => m.sv).concat(
  ['Vi tycker om katter.', 'Barnet ska läsa en bok.', 'jag köpte en såg', 'Hunden såg katten', 'ge den åt någon', 'det ska tystna',
   'Branden var stor', 'Kalle och Lisa går till Himlen', 'Mannen ser männen', 'två cyklar och han cyklar']);
const EN = ladda({ language: 'en-GB' }).G;
EN.setLang('en');
texts.push('We like cats', 'The children ate apples', 'I will read a book', 'The man saw the dog', 'She went home and slept');
let sentDiff = 0;
for (const t of texts) {
  for (const [l, ref] of [['sv', G], ['en', EN]]) {
    S.setLang(l);
    const a = S.writeWords(t, l), b = ref.writeWords(t, l);
    const ka = a.map((w) => [w.text, w.options.map(key), key(S.chosenOptions(a)[a.indexOf(w)])]);
    const kb = b.map((w) => [w.text, w.options.map(key), key(ref.chosenOptions(b)[b.indexOf(w)])]);
    if (!same(ka, kb)) { sentDiff++; console.log(`  differs (${l}):`, t); }
  }
}
if (sentDiff) throw new Error(`${sentDiff} sentences are written differently from Bliss-glosor`);
console.log(`writing rules: ${texts.length} sentences, Swedish and English, written exactly as in Bliss-glosor`);
